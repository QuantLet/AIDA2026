"""Stage 10 — LaTeX table fragments for the lecture deck.

Two tables, both written to tables/ as \\input-able fragments so no number on a slide is
typed by hand:

  backtest_SPX.tex          the headline table, nine models on the S&P 500
  backtest_all_assets.tex   the same battery on all five assets, breaches and rate

The five-asset table exists to answer the obvious question about the headline one: does
the S&P result replicate, or is it one market's accident? A model is scored only on the
dates it actually covers, and n is printed whenever it differs from the full span.

Usage:  python src/10_slide_tables.py
"""

